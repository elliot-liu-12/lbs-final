"""Evaluation driver: regenerates eval/results.md and eval/results.json.

    .venv/bin/python eval/run_eval.py [--trials 500] [--fuzz 1000]

1. Example suite: CT and NI verdicts vs. manually justified expectations and
   vs. ground truth (does the program actually leak under the CT model?),
   checking time, and dynamic two-run testing.
2. Random-program fuzzing of the soundness claim.
3. Checking-time scaling on synthetic programs of increasing size.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ctcheck import Mode, check, parse  # noqa: E402
from ctcheck.examples import all_examples  # noqa: E402
from ctcheck.progen import random_program  # noqa: E402
from ctcheck.relational import compare, search_leak  # noqa: E402


def timed(fn, reps):
    samples = []
    for _ in range(reps):
        t0 = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - t0)
    return statistics.median(samples) * 1000


def outcome(rejected: bool, leaks: bool) -> str:
    return {(True, True): "TP", (False, False): "TN", (True, False): "FP", (False, True): "FN"}[(rejected, leaks)]


def eval_examples(trials: int):
    rows = []
    for ex in all_examples():
        src = ex.path.read_text()
        prog = parse(src)
        ct, ni = check(prog, Mode.CT), check(prog, Mode.NI)
        if ex.witness is not None:
            div = compare(prog, {}, *ex.witness)
            dyn = "witness (hand-picked inputs)" if div else "none"
            dyn_found, dyn_trials = div is not None, 1
        else:
            ls = search_leak(prog, trials=trials, seed=0)
            dyn_found, dyn_trials = ls.leaked, ls.trials
            dyn = f"{ls.divergence.kind} after {ls.trials} trials" if ls.leaked else f"none in {trials}"
        rows.append({
            "example": ex.name,
            "category": ex.category,
            "loc": sum(1 for l in src.splitlines() if l.strip() and not l.strip().startswith("//")),
            "leaks": ex.leaks,
            "ct_ok": ct.ok, "ct_codes": ct.codes, "ct_expected": ct.ok == ex.ct_accept and set(ct.codes) == ex.ct_codes,
            "ni_ok": ni.ok, "ni_codes": ni.codes, "ni_expected": ni.ok == ex.ni_accept and set(ni.codes) == ex.ni_codes,
            "ct_outcome": outcome(not ct.ok, ex.leaks),
            "ni_outcome": outcome(not ni.ok, ex.leaks),
            "parse_ms": timed(lambda: parse(src), 50),
            "check_ms": timed(lambda: check(prog, Mode.CT), 200),
            "dynamic": dyn, "dynamic_leak": dyn_found, "dynamic_trials": dyn_trials,
        })
    return rows


def eval_fuzz(n: int, trials: int):
    acc = rej = rej_witnessed = unsound = 0
    ct_not_ni = 0
    for seed in range(n):
        p = random_program(seed)
        ct, ni = check(p, Mode.CT), check(p, Mode.NI)
        if ct.ok and not ni.ok:
            ct_not_ni += 1
        leaked = search_leak(p, trials=trials, seed=seed).leaked
        if ct.ok:
            acc += 1
            unsound += leaked
        else:
            rej += 1
            rej_witnessed += leaked
    return {"programs": n, "trials_per_program": trials, "accepted": acc, "rejected": rej,
            "rejected_with_witness": rej_witnessed, "rejected_no_witness": rej - rej_witnessed,
            "accepted_with_witness (soundness violations)": unsound, "ct_ok_but_ni_rejects": ct_not_ni}


def synthetic(n_stmts: int) -> str:
    lines = ["public int p; secret int s; public int[16] pa; secret int[16] sa;"]
    for k in range(n_stmts):
        r = k % 4
        if r == 0:
            lines.append(f"s := select(s & {k}, sa[{k % 16}], s ^ pa[p & 15]);")
        elif r == 1:
            lines.append(f"for i in 0 .. 4 {{ sa[i] := sa[i] + s * {k}; }}")
        elif r == 2:
            lines.append(f"if (p > {k}) {{ p := p - 1; }} else {{ s := s + p; }}")
        else:
            lines.append(f"p := (p * 31 + {k}) & 255;")
    return "\n".join(lines)


def eval_scaling():
    rows = []
    for n in (10, 100, 1000, 10000):
        src = synthetic(n)
        prog = parse(src)
        assert check(prog).ok
        reps = max(3, 2000 // n)
        rows.append({"statements": n, "parse_ms": timed(lambda: parse(src), max(3, reps // 4)),
                     "check_ms": timed(lambda: check(prog), reps)})
    return rows


def markdown(rows, fuzz, scaling, trials) -> str:
    def yn(b):
        return "yes" if b else "no"

    out = ["# Evaluation results", "",
           "Generated by `eval/run_eval.py`. Ground truth (`leaks`) is the manual justification in each "
           "example's header: whether two runs that agree on public inputs can produce different "
           "observations (branch outcomes, loop counts, memory addresses, modeled cost, public outputs).", "",
           "## Example suite", "",
           "| example | category | LoC | leaks | CT verdict | NI verdict | matches expected | CT check (ms) | two-run testing |",
           "|---|---|---:|:-:|---|---|:-:|---:|---|"]
    for r in rows:
        ctv = "accept" if r["ct_ok"] else "reject " + ",".join(r["ct_codes"])
        niv = "accept" if r["ni_ok"] else "reject " + ",".join(r["ni_codes"])
        match = "✓" if r["ct_expected"] and r["ni_expected"] else "✗"
        out.append(f"| {r['example']} | {r['category']} | {r['loc']} | {yn(r['leaks'])} | {ctv} | {niv} | "
                   f"{match} | {r['check_ms']:.3f} | {r['dynamic']} |")

    def confusion(key):
        c = {k: sum(r[key] == k for r in rows) for k in ("TP", "TN", "FP", "FN")}
        return c

    ct, ni = confusion("ct_outcome"), confusion("ni_outcome")
    out += ["", "## Verdicts against ground truth", "",
            "| checker | leaky & rejected (TP) | safe & accepted (TN) | safe but rejected (conservative, FP) | leaky but accepted (FN) |",
            "|---|---:|---:|---:|---:|",
            f"| CT mode | {ct['TP']} | {ct['TN']} | {ct['FP']} | {ct['FN']} |",
            f"| NI mode (baseline) | {ni['TP']} | {ni['TN']} | {ni['FP']} | {ni['FN']} |", ""]
    matched = sum(r["ct_expected"] and r["ni_expected"] for r in rows)
    out.append(f"- {matched}/{len(rows)} examples match their expected verdict and diagnostic codes in both modes.")
    cons = [r["example"] for r in rows if r["ct_outcome"] == "FP"]
    out.append(f"- Conservative CT rejections ({len(cons)}): {', '.join(cons)}.")
    ni_miss = [r["example"] for r in rows if r["ni_outcome"] == "FN"]
    out.append(f"- Leaks the NI baseline misses ({len(ni_miss)}): {', '.join(ni_miss)} — all are timing/address "
               "leaks that do not affect the final public state.")
    dyn_missed = [r["example"] for r in rows if r["leaks"] and not r["dynamic_leak"]]
    hp = [r["example"] for r in rows if r["dynamic"].startswith("witness")]
    random_hits = sum(r["leaks"] and r["dynamic_leak"] and r["example"] not in hp for r in rows)
    out.append(f"- Random two-run testing ({trials} trials) witnessed {random_hits}/{sum(r['leaks'] for r in rows)} "
               f"leaky examples and never reported a divergence for an accepted program.")
    if hp:
        out.append(f"- Needed hand-picked inputs to witness: {', '.join(hp)} — a leak the type checker catches "
                   "but random testing is very unlikely to hit.")
    total = sum(r["check_ms"] for r in rows)
    out.append(f"- Total CT checking time for all {len(rows)} examples: {total:.2f} ms "
               f"(median per example {statistics.median(r['check_ms'] for r in rows):.3f} ms; parsing excluded).")

    out += ["", "## Random-program fuzzing of soundness", "",
            "| metric | value |", "|---|---:|"]
    out += [f"| {k} | {v} |" for k, v in fuzz.items()]
    out += ["", "Rejected programs without a witnessed leak are either conservative rejections or leaks "
            "that random testing did not find; accepted programs with a witness would be soundness bugs.", "",
            "## Checking-time scaling (synthetic CT-safe programs)", "",
            "| statements | parse (ms) | check (ms) |", "|---:|---:|---:|"]
    out += [f"| {r['statements']} | {r['parse_ms']:.2f} | {r['check_ms']:.3f} |" for r in scaling]
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trials", type=int, default=500)
    ap.add_argument("--fuzz", type=int, default=1000)
    ap.add_argument("--fuzz-trials", type=int, default=30)
    args = ap.parse_args()
    rows = eval_examples(args.trials)
    fuzz = eval_fuzz(args.fuzz, args.fuzz_trials)
    scaling = eval_scaling()
    here = Path(__file__).resolve().parent
    (here / "results.json").write_text(json.dumps({"examples": rows, "fuzz": fuzz, "scaling": scaling}, indent=2))
    md = markdown(rows, fuzz, scaling, args.trials)
    (here / "results.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
